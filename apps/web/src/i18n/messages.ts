export const MESSAGES: Record<Locale, Messages> = { en, tr };

export type Vars = Record<string, string | number>;

export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && (LOCALES as readonly string[]).includes(value);
}

/** Look up a message and fill `{name}` placeholders. Unknown keys fall back to English. */
export function translate(locale: Locale, key: MessageKey, vars?: Vars): string {
  const template = MESSAGES[locale][key] ?? en[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, name: string) =>
    name in vars ? String(vars[name]) : m,
  );
}

/** For enum-like values from the engine (e.g. "status.failed"); falls back to the raw value. */
export function translateEnum(locale: Locale, prefix: string, value: string, vars?: Vars): string {
  const key = `${prefix}.${value}`;
  if (key in en) return translate(locale, key as MessageKey, vars);
  return value.replace(/_/g, " ");
}

/** Pick a locale from an Accept-Language header (e.g. "tr-TR,tr;q=0.9,en;q=0.8"). */
export function localeFromAcceptLanguage(header: string | null | undefined): Locale {
  if (!header) return DEFAULT_LOCALE;
  const ranked = header
    .split(",")
    .map((part) => {
      const [tag, ...params] = part.trim().split(";");
      const q = params.find((p) => p.trim().startsWith("q="));
      return { tag: (tag ?? "").toLowerCase(), q: q ? Number(q.trim().slice(2)) || 0 : 1 };
    })
    .sort((a, b) => b.q - a.q);
  for (const { tag } of ranked) {
    const base = tag.split("-")[0];
    if (isLocale(base)) return base;
  }
  return DEFAULT_LOCALE;
}
