import { describe, expect, it } from "vitest";
import { safeSnippet } from "@webdna/shared";
import { bundleFromHtml } from "../src/index.js";
import { analyze, registry } from "./helpers.js";

const page = (
  head: string,
  body = "<p>Enough visible words to count as page content for coverage.</p>",
) => `<html><head><title>t</title>${head}</head><body>${body}</body></html>`;

function run(
  html: string,
  url = "https://shop.example.com/",
  extra: { scripts?: { url: string; text: string; comments: string[] }[] } = {},
) {
  const b = bundleFromHtml(html, {
    url,
    selectors: registry.requiredSelectors(),
    scriptSources: extra.scripts,
  });
  return analyze(b);
}

describe("pre-release audit regressions: AI attribution", () => {
  it.each([
    "<!-- Made by Claude Dupont, Lyon -->",
    "<!-- Built with lovable care by our team -->",
    "<!-- Site created by Gemini Studio (a design agency) -->",
    "<!-- Written by the Copilot Travel team -->",
    "<!-- Theme made by Cursor Creative -->",
  ])("does not treat a person or company name as an AI marker: %s", (comment) => {
    const r = run(page("", `${comment}<p>Enough visible words to count as page content here.</p>`));
    expect(r.aiFindings).toEqual([]);
  });

  it.each([
    ["<!-- Generated with Lovable -->", "Lovable"],
    ["<!-- This page was generated by Claude Code -->", "Claude Code"],
    ["<!-- Built with GitHub Copilot -->", "GitHub Copilot"],
  ])("still reports explicit tool markers: %s", (comment) => {
    const r = run(page("", `${comment}<p>Enough visible words to count as page content here.</p>`));
    expect(r.aiFindings.length).toBeGreaterThan(0);
  });

  it("caps AI markers found only in third-party scripts at weak and says so", () => {
    const r = run(
      page('<script src="https://widget.thirdparty-chat.net/embed.js"></script>'),
      "https://shop.example.com/",
      {
        scripts: [
          {
            url: "https://widget.thirdparty-chat.net/embed.js",
            text: "/* Generated with Lovable */",
            comments: ["Generated with Lovable"],
          },
        ],
      },
    );
    const f = r.aiFindings.find((x) => x.detectorId === "ai.explicit-generator-marker")!;
    expect(f.evidenceStrength).toBe("weak");
    expect(f.limitations.join(" ")).toMatch(/third-party/);
    expect(r.conclusion).toBe("weak_or_ambiguous");
  });

  it("does not identify a platform from path-only patterns on third-party assets", () => {
    const r = run(
      page(
        '<script src="https://widgets.othersite.io/_next/static/chunks/widget.js"></script><link rel="stylesheet" href="https://cdn.partner.org/wp-content/themes/x.css">',
      ),
    );
    const names = r.platformFindings.map((f) => f.subject);
    expect(names).not.toContain("Next.js");
    expect(names).not.toContain("WordPress");
  });

  it("still identifies a platform from first-party (same-site) asset paths", () => {
    const r = run(
      page('<script src="https://static.example.com/_next/static/chunks/main.js"></script>'),
    );
    expect(r.platformFindings.map((f) => f.subject)).toContain("Next.js");
  });
});

describe("pre-release audit regressions: sensitive data in snippets", () => {
  it.each([
    ["https://cdn.example.com/a.js?token=abc123def456&v=2", "abc123def456"],
    [
      "https://x.example/p?X-Amz-Signature=deadbeefcafe1234&X-Amz-Credential=AKIDEXAMPLE",
      "deadbeefcafe1234",
    ],
    ["https://x.example/cb?code=s3cr3tc0de&state=1", "s3cr3tc0de"],
    ["https://x.example/a?session_id=XYZsess99", "XYZsess99"],
  ])("redacts credential-like query values in %s", (url, secret) => {
    const out = safeSnippet(url);
    expect(out).not.toContain(secret);
    expect(out).toContain("[redacted]");
  });

  it("keeps non-sensitive query parameters", () => {
    expect(safeSnippet("/placeholder.svg?height=400&width=600")).toBe(
      "/placeholder.svg?height=400&width=600",
    );
  });
});
