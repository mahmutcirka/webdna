/**
 * Generates the example report shown on the landing page by running the real
 * pipeline against the synthetic "basic-landing" fixture. The output is labelled as
 * sample data; it is not a scan of any real website.
 *
 *   npm run sample-report
 */
import { copyFileSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { createDefaultRegistry } from "@webdna/detectors";
import { NetworkPolicy, runScan } from "@webdna/analysis-core";
import { REPO_ROOT, startFixtureServer } from "../tests/integration/fixture-server.js";

const server = await startFixtureServer("basic-landing");
const out = mkdtempSync(path.join(os.tmpdir(), "webdna-sample-"));
try {
  const report = await runScan({
    scanId: "sample-basic-landing",
    url: server.url,
    viewports: ["desktop", "tablet", "mobile"],
    outputDir: out,
    policy: new NetworkPolicy({
      unsafeAllowLoopback: [`127.0.0.1:${server.port}`],
      resolver: async () => {
        throw new Error("offline");
      },
    }),
    registry: createDefaultRegistry(),
  });
  report.sample = {
    label:
      "Example data — generated by WebDNA from a synthetic local fixture (fixtures/sites/basic-landing), not from a real website.",
  };
  const webDir = path.join(REPO_ROOT, "apps", "web");
  mkdirSync(path.join(webDir, "src", "sample"), { recursive: true });
  mkdirSync(path.join(webDir, "public", "sample"), { recursive: true });
  writeFileSync(
    path.join(webDir, "src", "sample", "sample-report.json"),
    `${JSON.stringify(report, null, 2)}\n`,
  );
  for (const v of report.viewports) {
    copyFileSync(
      path.join(out, v.screenshots.viewport),
      path.join(webDir, "public", "sample", v.screenshots.viewport),
    );
  }
  console.log(
    `Sample report written (${report.design.colors.length} colours, conclusion: ${report.aiOrigin.conclusionLabel}).`,
  );
} finally {
  await server.close();
  rmSync(out, { recursive: true, force: true });
}
